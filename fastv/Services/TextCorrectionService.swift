    /// 快速纠正文本中的错别字
    /// - Parameter text: 原始文本
    /// - Returns: 纠正后的文本
    func correctText(_ text: String) -> String {
        var correctedText = text
        
        // 1. 先处理词语级别的错误（更准确）
        for (wrong, correct) in wordTypoDict {
            if correctedText.contains(wrong) {
                correctedText = correctedText.replacingOccurrences(of: wrong, with: correct)
            }
        }
        
        // 2. 处理英语和日语的常见错误
        correctedText = correctEnglishTypos(correctedText)
        correctedText = correctJapaneseTypos(correctedText)
        
        // 3. 处理单字级别的错误
        // 注意：这里我们主要处理明显的错误，不改变正确的字
        // 因为很多"错别字"在特定语境下是正确的
        
        // 4. 清理多余的空格和标点
        correctedText = cleanText(correctedText)
        
        return correctedText
    }
    
